#!/usr/bin/env node
'use strict';

/**
 * tests/test_watermark_invariant.js — Verifies watermark branding invariants across the codebase.
 *
 * Guarantees:
 * 1. The only permitted watermark is "Build by Konoha shadow ninja with coffee by Andy Setiyawan".
 * 2. Zero legacy bare "Build by Konoha" watermarks exist in src/, bin/, or apps/.
 * 3. First-party binary assets contain zero AI model watermark markers.
 */

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const cp = require('child_process');

console.log('Running test_watermark_invariant: verifying branding and watermark invariants...');

const ROOT = path.resolve(__dirname, '..');
const EXPECTED_WATERMARK = 'Build by Konoha shadow ninja with coffee by Andy Setiyawan';

// 1. Verify build_spec.js and build_spec_common.js define the exact expected watermark
const buildSpec = fs.readFileSync(path.join(ROOT, 'src', 'mcp', 'build_spec.js'), 'utf8');
assert.ok(
  buildSpec.includes(EXPECTED_WATERMARK),
  `src/mcp/build_spec.js must contain expected watermark: "${EXPECTED_WATERMARK}"`
);

const buildSpecCommon = fs.readFileSync(path.join(ROOT, 'src', 'mcp', 'build_spec_common.js'), 'utf8');
assert.ok(
  buildSpecCommon.includes(EXPECTED_WATERMARK),
  `src/mcp/build_spec_common.js must contain expected watermark: "${EXPECTED_WATERMARK}"`
);
console.log('✓ Build spec directives enforce official watermark');

// 2. Verify jonin-skill references enforce the official watermark
const joninRefsDir = path.join(ROOT, 'src', 'templates', 'skills', 'jonin-skill', 'references');
const joninFiles = [
  'taste-skill-frontend-expert.md',
  'angular-code-expert.md',
  'nextjs-code-expert.md',
  'nuxt-code-expert.md',
  'svelte-code-expert.md',
  'build-directives-manifest.md',
];

for (const file of joninFiles) {
  const content = fs.readFileSync(path.join(joninRefsDir, file), 'utf8');
  assert.ok(
    content.includes(EXPECTED_WATERMARK),
    `${file} must specify official watermark: "${EXPECTED_WATERMARK}"`
  );
}
console.log('✓ All Jonin frontend skill references enforce official watermark');

// 3. Verify zero occurrences of bare "Build by Konoha" outside node_modules
const checkDirs = ['src', 'bin', 'apps'];
for (const dir of checkDirs) {
  const fullPath = path.join(ROOT, dir);
  if (!fs.existsSync(fullPath)) continue;

  function scanForBare(currentDir) {
    const entries = fs.readdirSync(currentDir, { withFileTypes: true });
    for (const entry of entries) {
      const entryPath = path.join(currentDir, entry.name);
      if (entry.isDirectory()) {
        scanForBare(entryPath);
      } else if (/\.(js|ts|svelte|md|html|json)$/.test(entry.name)) {
        const text = fs.readFileSync(entryPath, 'utf8');
        // Match "Build by Konoha" not followed by "shadow ninja"
        const bareMatch = text.match(/Build by Konoha(?! shadow ninja)/);
        assert.ok(
          !bareMatch,
          `Found legacy bare watermark in ${path.relative(ROOT, entryPath)}: "${bareMatch ? bareMatch[0] : ''}"`
        );
      }
    }
  }

  scanForBare(fullPath);
}
console.log('✓ Zero bare "Build by Konoha" watermarks in src/, bin/, or apps/');

// 4. Verify first-party image binary assets contain zero AI model watermarks
const assetFiles = fs.readdirSync(path.join(ROOT, 'assets')).filter(f => /\.(webp|png|jpg|jpeg)$/.test(f));
for (const file of assetFiles) {
  const filePath = path.join(ROOT, 'assets', file);
  try {
    const stringsOutput = cp.execSync(`strings "${filePath}"`, { encoding: 'latin1' });
    const aiMarker = stringsOutput.match(/(openai|anthropic|chatgpt|midjourney|dall-e|generated by claude|generated by gpt)/i);
    assert.ok(
      !aiMarker,
      `AI watermark detected in ${file}: ${aiMarker ? aiMarker[0] : ''}`
    );
  } catch (_) {
    // strings command unavailable or error; ignore
  }
}
console.log('✓ First-party assets contain zero AI model watermarks');

console.log('\nAll test_watermark_invariant checks passed cleanly!');
